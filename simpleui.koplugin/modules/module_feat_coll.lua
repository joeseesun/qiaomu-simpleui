-- module_feat_coll.lua — Simple UI
-- Module: Featured Collection (dynamic instances).
--
-- Same presentation as TBR/Recent/New Books (horizontal row
-- of up to 5 covers — engine shared in sui_book_grid.lua), but each instance
-- is linked to ANY collection that exists in ReadCollection, chosen
-- by the user — not just "To Be Read".
--
-- Difference from module_collections.lua: that one is a grid with up to 5
-- different collections at once (1 cover per collection). This module is
-- the opposite: 1 collection, several covers — and, like Quick Actions Row,
-- you can have N instances on your homescreen (one per collection you want
-- to feature).
--
-- Exposes M.instanciable = true and M.makeInstance(id) for the registry.
-- Instances persist in "simpleui_coll_row_instances" (M.instances_key).

local _  = require("infra/sui_i18n").translate

local CenterContainer = require("ui/widget/container/centercontainer")
local Font            = require("ui/font")
local Geom            = require("ui/geometry")

local Config      = require("infra/sui_config")
local SUISettings = require("infra/sui_store")
local SUIStyle    = require("features/sui_style")
local Chrome       = require("features/sui_module_chrome")
local UI          = require("infra/sui_core")
local GridRenderer = require("engines/sui_book_grid")
local Sources = require("engines/sui_book_sources")
local SourceMenu = require("features/sui_source_menu")

local PAD = UI.PAD

local MAX_ITEMS = 5

-- ---------------------------------------------------------------------------
-- Instance factory
-- ---------------------------------------------------------------------------
local function makeInstance(inst_id)
    local COLL_KEY = inst_id .. "_coll_name"

    local function getCollName(pfx)
        return SUISettings:readSetting(pfx .. COLL_KEY)
    end
    local function setCollName(pfx, name)
        SUISettings:saveSetting(pfx .. COLL_KEY, name)
    end

    local SORT_STATE_KEY = inst_id .. "_sort_state"

    -- Section label: the chosen collection (flagged when it no longer exists)
    -- or a configuration hint when none has been chosen yet.
    local function displayName(pfx)
        local name = getCollName(pfx)
        if not name then return _("Featured Collection — tap to configure") end
        return Sources.label("collection", { coll = name })
    end

    local source = Sources.bind("collection", function(ctx)
        return { coll = getCollName(ctx.pfx) }
    end)

    -- ── Featured Collection-specific menu items: collection picker,
    --    Sort and Arrange. Prepended to the generic items (Scale/Frame/...)
    --    generated by makeModule. ──────────────────────────────────────────
    local function extraMenuItemsBefore(ctx_menu)
        local _lc         = ctx_menu._
        local refresh      = ctx_menu.refresh
        local pfx          = ctx_menu.pfx
        local items = {}

        -- Choosing the target collection (single-select, radio). Implemented as
        -- a submenu (not item_picker) because it works identically in
        -- KOReader's native menu and in SUIWindow, without depending on a
        -- nested navigation context (push/pop). The collection list is read
        -- only when the submenu opens; the row value is the stored name.
        items[#items + 1] = Config.makeRadioSubmenuItem{
            text          = _lc("Collection"),
            separator     = true,
            options       = function()
                local options = {}
                for _i, name in ipairs(Sources.listCollectionNames()) do
                    options[#options + 1] = { value = name, label = name }
                end
                return options
            end,
            empty_text    = _lc("No collections found."),
            current_label = function() return getCollName(pfx) end,
            get           = function() return getCollName(pfx) end,
            set           = function(name) setCollName(pfx, name) end,
            refresh       = refresh,
        }

        -- Sort (rewrites the persisted order; manual Arrange remains
        -- available on top of the result) and Arrange.
        for _i, item in ipairs(SourceMenu.collectionItems(ctx_menu, "collection",
            function() return { coll = getCollName(pfx) } end,
            { sort = SourceMenu.keyedState(pfx .. SORT_STATE_KEY) })) do
            items[#items + 1] = item
        end

        return items
    end

    local mod = GridRenderer.makeModule{
        id          = inst_id,
        name        = _("Featured Collection"),
        default_on  = false,
        is_book_mod = true,   -- needed for the surgical repaint of the swipe
        max_items   = MAX_ITEMS,
        paged       = true,
        label_fn    = displayName,
        getFileList = source.getFileList,
        extra_menu_items_before = extraMenuItemsBefore,

        -- Library-style corner badges (see engines/sui_book_grid.lua's
        -- GridRenderer.applyBadges) — same defaults as Flat Library: all
        -- three off, user-editable, nothing pre-enabled.
        badges = { pages = "off", series = "off", new = "off" },
        -- No toggles spec previously = default off, user-editable. Same
        -- intent expressed directly now (see GridRenderer.getProgressStyle).
        progress_style = { default = "none" },

        -- Opt-in grid (up to 3 rows x 4-5 columns, configurable in "Rows"/
        -- "Columns" in the module's menu). Default 1x5 replicates the previous
        -- behaviour byte-for-byte — it only changes when the user raises "Rows".
        grid          = true,
        default_rows  = 1,
        default_cols  = MAX_ITEMS,
    }

    -- "Not configured yet" notice, just like module_collections.lua when
    -- no collection is selected: without this, a Featured Collection that still has
    -- no collection chosen reserves the space (getHeight doesn't depend on the
    -- list) but paints nothing — a blank area with no explanation.
    local orig_build = mod.build
    function mod.build(w, ctx)
        local widget = orig_build(w, ctx)
        if widget then return widget end
        if getCollName(ctx.pfx) then return nil end -- collection chosen but empty: keeps the old behaviour

        local hold_on = SUISettings:nilOrTrue("simpleui_hs_settings_on_hold")
        local ph_text = hold_on and _("No collection selected  —  long press to configure")
                                 or _("No collection selected")
        return CenterContainer:new{
            dimen = Geom:new{ w = w, h = mod.getHeight(ctx) },
            UI.makeColoredText{
                text    = ph_text,
                face    = Font:getFace(SUIStyle.FACE_REGULAR, SUIStyle.FS_BODY),
                fgcolor = (ctx.ink or Chrome.PLAIN_INK).sub,
                width   = w - PAD * 2,
            },
        }
    end

    return mod
end

-- ---------------------------------------------------------------------------
-- Export
-- ---------------------------------------------------------------------------
local M = {}
M.id            = "coll_row"
M.name          = _("Featured Collection")
M.instanciable  = true
M.instances_key = "simpleui_coll_row_instances"
M.makeInstance  = makeInstance

-- Layout-editor summary of an instance: the collection it features.
function M.getSummary(inst_id, pfx)
    local name = SUISettings:readSetting(pfx .. inst_id .. "_coll_name")
    if name and name ~= "" then return name end
    return _("No collection selected")
end

return M
